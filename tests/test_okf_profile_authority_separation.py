_SRC_ROOT = Path(frutlups.__file__).resolve().parent

# The only product modules allowed to know the observation surface exists.
_ALLOWED_IMPORTERS = {"okf_profile.py", "__init__.py"}

_FIVE_PUBLIC_NAMES = (
    "OKF_PROFILE_OBSERVATION_CONTRACT_ID",
    "OKF_PROFILE_OBSERVATION_CONTRACT_VERSION",
    "OKFProfileObservation",
    "ProfileLayerResult",
    "observe_okf_profile_path",
)

# Every native authority module named by the accepted separation contract, plus
# the remaining product modules; the guard below scans all of them, and this
# list documents the modules whose isolation is contractual.
_AUTHORITY_MODULES = (
    "project.py",
    "orchestrator.py",
    "gate.py",
    "handoff.py",
    "journal.py",
    "layout.py",
    "cli.py",
    "prompts.py",
    "prompt_template.py",
    "review_prompt_template.py",
    "review_report.py",
    "self_report.py",
    "state.py",
    "artifacts.py",
    "_scaffold.py",
)


def _product_modules() -> list[Path]:
    return sorted(_SRC_ROOT.glob("*.py"))


class ObservationImportGuardTests(unittest.TestCase):
    def test_authority_module_list_is_current(self) -> None:
        names = {path.name for path in _product_modules()}
        missing = set(_AUTHORITY_MODULES) - names
        self.assertFalse(missing, f"contractual modules disappeared: {sorted(missing)}")

    def test_only_the_package_root_imports_the_observation_module(self) -> None:
        for module_path in _product_modules():
            if module_path.name in _ALLOWED_IMPORTERS:
                continue
            tree = ast.parse(module_path.read_text(encoding="utf-8"))
            for node in ast.walk(tree):
                if isinstance(node, ast.Import):
                    for alias in node.names:
                        self.assertNotIn(
                            "okf_profile",
                            alias.name,
                            f"{module_path.name} imports the observation module",
                        )
                elif isinstance(node, ast.ImportFrom):
                    module = node.module or ""
                    self.assertNotIn(
                        "okf_profile",
                        module,
                        f"{module_path.name} imports from the observation module",
                    )
                    for alias in node.names:
                        self.assertNotIn(
                            alias.name,
                            _FIVE_PUBLIC_NAMES,
                            f"{module_path.name} imports an observation name",
                        )

    def test_no_authority_module_references_the_observation_surface(self) -> None:
        # Stricter than the import scan: no identifier or attribute anywhere in
        # a non-allowed product module may name the observation module or any
        # of its five public names, so indirect access (getattr, frutlups.X)
        # is caught as well.
        watched = set(_FIVE_PUBLIC_NAMES) | {"okf_profile"}
        for module_path in _product_modules():
            if module_path.name in _ALLOWED_IMPORTERS:
                continue
            tree = ast.parse(module_path.read_text(encoding="utf-8"))
            for node in ast.walk(tree):
                if isinstance(node, ast.Name) and node.id in watched:
                    self.fail(f"{module_path.name} references {node.id}")
                if isinstance(node, ast.Attribute) and node.attr in watched:
                    self.fail(f"{module_path.name} references .{node.attr}")
                if isinstance(node, ast.Constant) and isinstance(node.value, str):
                    if node.value in _FIVE_PUBLIC_NAMES or node.value == "okf_profile":
                        self.fail(
                            f"{module_path.name} carries the literal {node.value!r}"
                        )

    def test_the_observation_module_imports_no_authority_module(self) -> None:
        # Separation is two-way: the observation must not read native state
        # either. Its only product import is the accepted YAML boundary.
        tree = ast.parse((_SRC_ROOT / "okf_profile.py").read_text(encoding="utf-8"))
        imported: set[str] = set()
        for node in ast.walk(tree):
            if isinstance(node, ast.Import):
                imported.update(alias.name for alias in node.names)
            elif isinstance(node, ast.ImportFrom):
                imported.add(node.module or "")
        frutlups_imports = {name for name in imported if name.startswith("frutlups")}
        self.assertEqual(frutlups_imports, {"frutlups._yaml"})

    def test_the_yaml_boundary_does_not_know_the_observation_exists(self) -> None:
        source = (_SRC_ROOT / "_yaml.py").read_text(encoding="utf-8")
        self.assertNotIn("okf_profile", source)
        for name in _FIVE_PUBLIC_NAMES:
            self.assertNotIn(name, source)


