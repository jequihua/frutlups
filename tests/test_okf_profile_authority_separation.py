"""Authority separation for the OKF/profile observation (M004-S02/S04).

The observation surface must be import-isolated and causally inert: no native
authority module may import it, reference it, or branch on its results, and
changing an artifact's OKF/profile outcome while holding its native content
constant must change no native result — prompt/report/verdict validity,
accepted-slice discovery, the planning frontier, the human gate, the step
actor, runner authorization, write permission, handoff rendering, the journal,
or generated bytes. This file proves the separation structurally (AST over
every product module) and behaviorally (mutation-style project matrices).
Fixture-corpus parity and the limit matrix live in
``test_okf_profile_fixture_parity.py``.
"""

