# Concept-frontmatter variants that move ONLY the OKF/profile observation.
# Each is a well-formed frame (native region facts stay constant); `{kind}`
# is the artifact's registry type.
_PROFILE_VARIANTS: dict[str, str] = {
    "legacy": "",
    "profile_valid": '---\ntype: {kind}\nframework_profile: "0.1-rc.1"\n---\n',
    "profile_version_invalid": '---\ntype: {kind}\nframework_profile: "9.9"\n---\n',
    "profile_type_invalid": '---\ntype: made_up\nframework_profile: "0.1-rc.1"\n---\n',
    "profile_subset_invalid": (
        '---\ntype: {kind}\nframework_profile: "0.1-rc.1"\ntags: [a, b]\n---\n'
    ),
}

_VARIANT_ROWS: dict[str, tuple[str, str | None, str, str | None]] = {
    "legacy": ("not_evaluated", None, "not_applicable", None),
    "profile_valid": ("pass", None, "pass", None),
    "profile_version_invalid": ("pass", None, "fail", "PROFILE_VERSION_UNSUPPORTED"),
    "profile_type_invalid": ("pass", None, "fail", "PROFILE_TYPE_UNSUPPORTED"),
    "profile_subset_invalid": ("pass", None, "fail", "PROFILE_YAML_OUT_OF_SUBSET"),
}

_FENCED_ROUTING_BODY = (
    "# Coding Prompt 012: Something\n\n"
    "Front matter:\n\n"
    "```yaml\n"
    "milestone: M004\n"
    "slice: M004-S01\n"
    "title: Something\n"
    "```\n\n"
    "## Body\n\nText.\n"
)

_FIXTURES = Path(__file__).resolve().parent / "fixtures" / "template_v3_driver_contract"


def _layers(observation: OKFProfileObservation) -> tuple[str, str | None, str, str | None]:
    return (
        observation.okf_concept.result,
        observation.okf_concept.reason,
        observation.framework_profile.result,
        observation.framework_profile.reason,
    )


def _observe_text(text: str) -> tuple[str, str | None, str, str | None]:
    with tempfile.TemporaryDirectory() as tmp:
        path = Path(tmp) / "artifact.md"
        path.write_text(text, encoding="utf-8", newline="\n")
        return _layers(observe_okf_profile_path(path))


class PromptValidityMutationTests(unittest.TestCase):
    def test_profile_variants_move_the_observation_but_never_prompt_routing(self) -> None:
        native_results = set()
        observations = set()
        for label, frame in _PROFILE_VARIANTS.items():
            with self.subTest(variant=label):
                text = frame.format(kind="coding_prompt") + _FENCED_ROUTING_BODY
                meta = _meta_text(text)
                native_results.add(
                    (meta.milestone_id, meta.slice_id, tuple(meta.errors))
                )
                observations.add(_observe_text(text))
                self.assertEqual(_observe_text(text), _VARIANT_ROWS[label])
        # One native answer across all five variants; five distinct
        # observations. The observation moved; routing did not.
        self.assertEqual(len(native_results), 1)
        self.assertEqual(native_results.pop(), ("M004", "M004-S01", ()))
        self.assertEqual(len(observations), len(_PROFILE_VARIANTS))

    def test_pinned_profile_valid_native_invalid_prompt_stays_native_invalid(self) -> None:
        pinned = _FIXTURES / "profile_valid_native_invalid_prompt.md"
        observation = observe_okf_profile_path(pinned)
        self.assertEqual(_layers(observation), ("pass", None, "pass", None))
        self.assertEqual(observation.execution_eligibility, "not_evaluated")
        meta = _meta_text(pinned.read_text(encoding="utf-8"))
        self.assertFalse(meta.valid)
        self.assertEqual(meta.milestone_id, "")
        self.assertEqual(meta.slice_id, "")
        self.assertIn("could not parse milestone_id from coding prompt", meta.errors)


class ReportAndVerdictMutationTests(unittest.TestCase):
    _REPORT_BODY = "# Review\n\n## Verdict\n\npass\n"

    def test_profile_variants_never_move_review_verdict_parsing(self) -> None:
        verdicts = set()
        for label, frame in _PROFILE_VARIANTS.items():
            with self.subTest(variant=label):
                text = frame.format(kind="review_report") + self._REPORT_BODY
                result = parse_review_report_verdict_text(text)
                verdicts.add((result.verdict, result.raw_verdict, tuple(result.errors)))
        self.assertEqual(len(verdicts), 1)

    def test_blocked_verdict_is_equally_unaffected(self) -> None:
        body = "# Review\n\n## Verdict\n\nblocked\n"
        results = {
            parse_review_report_verdict_text(frame.format(kind="review_report") + body).verdict
            for frame in _PROFILE_VARIANTS.values()
        }
        self.assertEqual(len(results), 1)


def _project_with_variant(root: Path, frame_template: str) -> None:
    """One accepted slice (M001-S01), live frontier at M001-S02; every
    artifact carries the variant's concept frontmatter above identical
    native content."""

    def frame(kind: str) -> str:
        return frame_template.format(kind=kind)

    _make_template(root)
    _write_active_roadmap(root, "### M001: Test\n\nStatus: active\n\n")
    _write_detailed_roadmap(
        root,
        "### M001: Test\n\nSlices:\n- M001-S01: first slice\n- M001-S02: second slice\n\n",
    )
    _write_coding_prompt(
        root,
        "001_first_slice.md",
        frame("coding_prompt") + _minimal_coding_prompt(1),
    )
    _write_self_report(
        root,
        "05_governance/reviews/m001_s01_first_slice_self_report.md",
        frame("self_report") + _minimal_self_report(),
    )
    _write_review_prompt(root, "001_review_something.md")
    (root / "05_governance" / "reviews" / "m001_s01_review_report.md").write_text(
        frame("review_report") + "# Review\n\n## Verdict\n\npass\n", encoding="utf-8"
    )
    (root / "05_governance" / "reviews" / "m001_s01_verdict_record.md").write_text(
        frame("verdict_record")
        + "# Verdict Record\n\n## Source\n\n"
        + "Review report: `05_governance/reviews/m001_s01_review_report.md`\n",
        encoding="utf-8",
    )


def _normalized_cli_state(root: Path) -> dict[str, str]:
    state: dict[str, str] = {}
    for verb in ("status", "next", "orchestrator-plan"):
        for extra in ((), ("--json",)):
            code, out, err = _run([verb, str(root), *extra])
            key = verb + ("+json" if extra else "")
            normalized = out.replace(str(root), "<ROOT>").replace(
                str(root).replace("\\", "\\\\"), "<ROOT>"
            ).replace(str(root).replace("\\", "/"), "<ROOT>")
            state[key] = f"rc={code}\n{normalized}\nerr={err}"
    return state


class ProjectAuthorityMutationTests(unittest.TestCase):
    """The same project under five profile variants yields identical native
    state: acceptance, frontier, gate, actor, journal, handoffs, and the
    bytes a mutating command writes."""

    def test_profile_variants_change_no_native_project_state(self) -> None:
        states: dict[str, dict[str, str]] = {}
        handoffs: dict[str, tuple[str, str]] = {}
        generated: dict[str, bytes] = {}
        for label, frame_template in _PROFILE_VARIANTS.items():
            with tempfile.TemporaryDirectory() as tmp:
                root = Path(tmp) / "proj"
                root.mkdir()
                _project_with_variant(root, frame_template)
                states[label] = _normalized_cli_state(root)
                coder = build_coder_handoff(root).content.replace(str(root), "<ROOT>")
                reviewer = build_reviewer_handoff(root).content.replace(
                    str(root), "<ROOT>"
                )
                handoffs[label] = (coder, reviewer)
                self.assertFalse((root / JOURNAL_REL_PATH).exists())
                # A mutating command still writes, and writes the same bytes.
                code, out, err = _run(["make-coding-prompt", str(root)])
                self.assertEqual(code, 0, (out, err))
                written = sorted(
                    (root / "prompts" / "for_coding_agent").glob("002_*.md")
                )
                self.assertEqual(len(written), 1)
                generated[label] = written[0].read_bytes()
                self.assertFalse((root / JOURNAL_REL_PATH).exists())
        baseline = states["legacy"]
        for label, state in states.items():
            with self.subTest(surface="cli", variant=label):
                self.assertEqual(state, baseline)
        for label, pair in handoffs.items():
            with self.subTest(surface="handoff", variant=label):
                self.assertEqual(pair, handoffs["legacy"])
        for label, content in generated.items():
            with self.subTest(surface="generated", variant=label):
                self.assertEqual(content, generated["legacy"])

    def test_observing_every_artifact_changes_no_state_or_byte(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp) / "proj"
            root.mkdir()
            _project_with_variant(root, _PROFILE_VARIANTS["profile_valid"])
            before_cli = _normalized_cli_state(root)
            snapshot = {
                path.relative_to(root).as_posix(): (
                    path.read_bytes(),
                    path.stat().st_mtime_ns,
                )
                for path in sorted(root.rglob("*"))
                if path.is_file()
            }
            for path in sorted(root.rglob("*.md")):
                observe_okf_profile_path(path)
            after = {
                path.relative_to(root).as_posix(): (
                    path.read_bytes(),
                    path.stat().st_mtime_ns,
                )
                for path in sorted(root.rglob("*"))
                if path.is_file()
            }
            self.assertEqual(snapshot, after)
            self.assertFalse((root / JOURNAL_REL_PATH).exists())
            self.assertEqual(_normalized_cli_state(root), before_cli)

    def test_native_paths_never_call_the_observation_even_when_it_raises(self) -> None:
        # Patch the observation to raise (and, in turn, to every result class):
        # no native surface may reach it, so nothing changes and nothing raises.
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp) / "proj"
            root.mkdir()
            _project_with_variant(root, _PROFILE_VARIANTS["profile_valid"])
            baseline = _normalized_cli_state(root)
            handoff = build_coder_handoff(root).content
            with mock.patch.object(
                frutlups.okf_profile,
                "observe_okf_profile_path",
                side_effect=AssertionError("a native path called the observation"),
            ), mock.patch.object(
                frutlups,
                "observe_okf_profile_path",
                side_effect=AssertionError("a native path called the observation"),
            ):
                self.assertEqual(_normalized_cli_state(root), baseline)
                self.assertEqual(build_coder_handoff(root).content, handoff)
                self.assertEqual(build_reviewer_handoff(root).content,
                                 build_reviewer_handoff(root).content)

    def test_status_json_carries_no_observation_key(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp) / "proj"
            root.mkdir()
            _project_with_variant(root, _PROFILE_VARIANTS["profile_valid"])
            _, out, _ = _run(["status", str(root), "--json"])
            payload = json.dumps(json.loads(out)).lower()
            for token in ("okf", "observe", "profile_observation", "framework_profile"):
                self.assertNotIn(token, payload)


